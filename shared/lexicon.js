/** 从一段自然语言中提取标签命中（返回 标签 → 权重） */
export function tagsForText(text) {
  const hits = new Map()
  if (!text) return hits
  const t = String(text)
  for (const [kw, tags] of Object.entries(KEYWORD_MAP)) {
    if (!t.includes(kw)) continue
    for (const tag of tags) hits.set(tag, (hits.get(tag) || 0) + 1)
  }
  return hits
}

