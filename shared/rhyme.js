/** 取某韵部某字数的韵脚词（含平仄过滤） */
export function tailPhrases(buId, len, toneFilter) {
  const g = RHYME_TAILS[buId]
  if (!g || !g[len]) return []
  const list = g[len]
  if (!toneFilter) return list
  // toneFilter 为「该字对应的谱符」，只需末字匹配
  return list.filter(([, tones]) => toneFilter(tones[tones.length - 1]))
}

/**
 * 「尾块落在某谱式位置上」时，该韵部能用的韵脚条目。
 * ─────────────────────────────────────────────────────────────
 * 这是把「重韵」从算法层面掐掉的基础接口：
 * 一句话末尾该押什么字，不完全取决于韵部，还取决于**尾块的谱式形状**——
 * 例如谱式收「◐●○」（第 6 位严格仄、末位严格平）时，
 * 东冬部里所有「●○○」形状的韵脚词（如「月明中」）都用不上，
 * 只有「●●○」「○●○」形状的才行。若不知道这一点，
 * 就会误以为东冬部有 9 个可用韵脚字，实际只有 1 个 → 必然重韵。
 *
 * @param buId    韵部 id
 * @param pattern 整句谱式（如 '◐●○○◐●○'）
 * @param offset  尾块在整句里的起始下标
 * @returns 可用条目 [ [词, 平仄串, ...tags], ... ]
 */
export function tailEntriesAt(buId, pattern, offset) {
  const len = pattern.length - offset
  const list = (RHYME_TAILS[buId] || {})[len] || []
  const lineLen = pattern.length
  const out = []
  for (const it of list) {
    const tones = it[1]
    if (tones.length !== len) continue
    let bad = false
    for (let i = 0; i < len; i++) {
      const pc = pattern[offset + i]
      if (pc === '◐' || tones[i] === '◐') continue
      const pos = offset + i + 1
      const strict = pos % 2 === 0 || pos === lineLen
      if (pc !== tones[i] && strict) {
        bad = true
        break
      }
    }
    if (!bad) out.push(it)
  }
  return out
}

/** 同上，只取「不同的韵脚末字」集合 */
export function tailCharsAt(buId, pattern, offset) {
  return new Set(tailEntriesAt(buId, pattern, offset).map((it) => [...it[0]].pop()))
}

