export const BU_BY_ID = Object.fromEntries(RHYME_BU.map((b) => [b.id, b]))

/** 字 → 所属韵部（可能多部） */
const INDEX = new Map()
for (const bu of RHYME_BU) {
  for (const ch of bu.chars) {
    if (!INDEX.has(ch)) INDEX.set(ch, [])
    INDEX.get(ch).push(bu.id)
  }
}

export function lookupChar(ch) {
  return INDEX.get(ch) || []
}

export function lookupWord(word) {
  const out = []
  for (const ch of word) {
    for (const id of lookupChar(ch)) {
      if (!out.some((o) => o.bu === id)) out.push({ bu: id, ch })
    }
  }
  return out
}

/** 按韵部取字数组 */
export function charsOf(buId) {
  const b = BU_BY_ID[buId]
  return b ? b.chars : []
}

/** 平声韵部 / 仄声韵部 */
export const PING_BU = RHYME_BU.filter((b) => b.tone === '平')
export const ZE_BU = RHYME_BU.filter((b) => b.tone === '仄')

/** 随机取一字（从韵部字表中） */
export function randomChar(buId, rnd = Math.random) {
  const cs = charsOf(buId)
  if (!cs.length) return null
  return cs[Math.floor(rnd() * cs.length)]
}

