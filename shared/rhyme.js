/** 规范化过程中被丢弃的条目（脚本可读，用于体检） */
export const RHYME_ISSUES = []

const TONE_SYM = { 平: '○', 仄: '●' }

/** 字 → 它出现在哪些韵部（可能多部；用于把放错部的韵脚条目迁回去） */
const CHAR_BU = new Map()
for (const bu of RHYME_BU) {
  for (const ch of bu.chars) {
    if (!CHAR_BU.has(ch)) CHAR_BU.set(ch, [])
    if (!CHAR_BU.get(ch).includes(bu.id)) CHAR_BU.get(ch).push(bu.id)
  }
}

/**
 * 韵脚词表的自检与规范化
 * ─────────────────────────────────────────────────────────────
 * 这份词表是手工整理的，历史上攒下四类毛病：
 *   ① 条目放错字数桶（三个字的「相思泪」塞在 2 字桶里）；
 *   ② 条目放错韵部（「小楼」写在寒删先部，可「楼」属尤侯）；
 *   ③ 末字的平仄与所在部的声调相反（「几时」是平声，却混进仄声第三部）；
 *   ④ 平仄串里末字那个符号写反了（「夜深」标成「●●」，可「深」是平声）。
 *
 * 这些条目在生成时会被静默跳过，后果不是报错，而是
 * **韵脚候选池被悄悄抽干**——引擎找不到没用过的韵脚字，只好重复，
 * 于是出现重韵（词的硬伤）。所以这里不逐条人工纠错，改成加载时重排：
 *
 *   · 平仄串长度必须等于词长 → 否则丢弃；
 *   · 末字本来就在本部字表里 → 只把末位平仄符号改成与本部一致（修 ④）；
 *   · 末字不在本部，但在别的「声调相符」的部里 → 迁过去（修 ②）；
 *   · 末字只出现在唯一一个部（声调不相符也算）→ **信字不信符号**：
 *     按那个部的声调改正平仄串并迁过去（修 ③④）。字的归属比手打的符号可靠。
 *   · 末字在所有韵部字表里都找不到 → 丢弃，理由记进 RHYME_ISSUES。
 *   · 最后按「词长」重新分桶（修 ①）。
 *
 * 这样修一次，以后往词表里加词也不会再把库弄脏。
 */
function normalizeTails() {
  const buckets = {}
  for (const bu of RHYME_BU) buckets[bu.id] = {}

  for (const bu of RHYME_BU) {
    const raw = RHYME_TAILS[bu.id] || {}
    const want = TONE_SYM[bu.tone]
    const charset = new Set(bu.chars)

    for (const list of Object.values(raw)) {
      for (const item of list) {
        if (!Array.isArray(item) || typeof item[0] !== 'string' || typeof item[1] !== 'string') continue
        const [word, tones] = item
        const wLen = [...word].length
        const tLen = [...tones].length
        if (wLen !== tLen) {
          RHYME_ISSUES.push({ bu: bu.id, word, why: '平仄串长度与词长不符，已丢弃' })
          continue
        }
        const last = [...word][wLen - 1]
        let lastTone = tones[tLen - 1]

        let home = null
        let fixedTone = false
        if (charset.has(last)) {
          home = bu.id
          if (lastTone !== want) {
            fixedTone = true
            lastTone = want
          }
        } else {
          const homes = CHAR_BU.get(last) || []
          const alts = homes.filter((id) => TONE_SYM[BU_BY_ID[id].tone] === lastTone)
          if (alts.length) {
            home = alts.includes(bu.id) ? bu.id : alts[0]
            RHYME_ISSUES.push({
              bu: bu.id,
              word,
              why: `末字「${last}」不属本部，已迁往 ${home}`,
              moved: home
            })
          } else if (homes.length === 1) {
            // 字只此一部：说明是手打的平仄符号错了，跟着字走
            home = homes[0]
            lastTone = TONE_SYM[BU_BY_ID[home].tone]
            fixedTone = true
            RHYME_ISSUES.push({
              bu: bu.id,
              word,
              why: `末字「${last}」只属 ${home}，已按字迁部并改正平仄`,
              moved: home
            })
          } else {
            RHYME_ISSUES.push({
              bu: bu.id,
              word,
              why: `末字「${last}」在现有韵部字表里找不到住所，已丢弃`
            })
          }
        }
        if (!home) continue

        if (fixedTone) {
          const chars = [...tones]
          chars[tLen - 1] = lastTone
          item[1] = chars.join('')
        }

        const b = buckets[home]
        if (!b[wLen]) b[wLen] = []
        if (!b[wLen].some((x) => x[0] === word && x[1] === item[1])) b[wLen].push(item)
      }
    }
  }

  for (const bu of RHYME_BU) RHYME_TAILS[bu.id] = buckets[bu.id]
}
normalizeTails()

/** 韵脚库体检报告：每个韵部可用多少个「不同的韵脚字」（决定最多能押几句不重字） */
export function rhymeTailStats() {
  const out = []
  for (const bu of RHYME_BU) {
    const g = RHYME_TAILS[bu.id] || {}
    const per = {}
    const union = new Set()
    for (const [len, list] of Object.entries(g)) {
      const s = new Set(list.map((it) => [...it[0]].pop()))
      per[len] = { entries: list.length, distinct: s.size, chars: [...s].join('') }
      for (const c of s) union.add(c)
    }
    out.push({
      id: bu.id,
      name: bu.name,
      short: bu.short,
      tone: bu.tone,
      totalDistinct: union.size,
      allChars: [...union].join(''),
      per
    })
  }
  return out
}

